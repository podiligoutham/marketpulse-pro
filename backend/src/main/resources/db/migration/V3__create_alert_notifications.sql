CREATE TABLE alert_notifications
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    alert_id        BIGINT         NOT NULL
        REFERENCES price_alerts (id),

    symbol          VARCHAR(20)    NOT NULL,

    triggered_price NUMERIC(19, 4) NOT NULL,

    observed_at     TIMESTAMPTZ    NOT NULL,

    created_at      TIMESTAMPTZ    NOT NULL
                                            DEFAULT CURRENT_TIMESTAMP,

    status          VARCHAR(20)    NOT NULL DEFAULT 'PENDING',

    delivered_at    TIMESTAMPTZ,

    CONSTRAINT uq_alert_notifications_alert_id
        UNIQUE (alert_id),

    CONSTRAINT chk_alert_notification_status
        CHECK (status IN ('PENDING', 'DELIVERED'))
);

CREATE INDEX idx_alert_notifications_pending
    ON alert_notifications (created_at, id) WHERE status = 'PENDING';
