CREATE TABLE price_alerts
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    symbol       VARCHAR(20)    NOT NULL,

    condition    VARCHAR(10)    NOT NULL,

    target_price NUMERIC(19, 4) NOT NULL,

    status       VARCHAR(20)    NOT NULL DEFAULT 'ACTIVE',

    created_at   TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    triggered_at TIMESTAMPTZ,

    CONSTRAINT chk_price_alert_condition
        CHECK (condition IN ('ABOVE', 'BELOW')),

    CONSTRAINT chk_price_alert_status
        CHECK (status IN ('ACTIVE', 'TRIGGERED')),

    CONSTRAINT chk_price_alert_target
        CHECK (target_price > 0),

    CONSTRAINT chk_price_alert_triggered_at
        CHECK (
            (status = 'ACTIVE' AND triggered_at IS NULL)
                OR
            (status = 'TRIGGERED' AND triggered_at IS NOT NULL)
            )
);

CREATE INDEX idx_price_alerts_active_symbol
    ON price_alerts (symbol) WHERE status = 'ACTIVE';
